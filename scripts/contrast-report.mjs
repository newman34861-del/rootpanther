import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const css = readFileSync(`${root}packages/ui/theme.css`, "utf8");

function block(selector) {
  const start = css.indexOf(selector);
  const body = css.slice(css.indexOf("{", start) + 1, css.indexOf("\n}", start));
  return Object.fromEntries([...body.matchAll(/(--[\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
}

const dark = block(":root {");
const light = { ...dark, ...block('[data-theme="light"] {') };

function resolve(table, v) {
  let out = v;
  for (let i = 0; i < 10 && out.startsWith("var("); i++) out = table[out.slice(4, -1).trim()];
  return out;
}

function parse(c, table) {
  const mix = c.match(/^color-mix\(in srgb,\s*(var\([^)]+\)|#[0-9a-f]+)\s+(\d+)%,\s*(var\([^)]+\)|#[0-9a-f]+)\)$/i);
  if (mix) {
    const a = parse(resolve(table, mix[1]), table);
    const b = parse(resolve(table, mix[3]), table);
    const p = Number(mix[2]) / 100;
    return [a[0] * p + b[0] * (1 - p), a[1] * p + b[1] * (1 - p), a[2] * p + b[2] * (1 - p), 1];
  }
  if (c.startsWith("#")) {
    const h = c.slice(1);
    const n = h.length === 3 ? h.split("").map((x) => x + x).join("") : h;
    return [parseInt(n.slice(0, 2), 16), parseInt(n.slice(2, 4), 16), parseInt(n.slice(4, 6), 16), 1];
  }
  const m = c.match(/rgba?\(([^)]+)\)/);
  const p = m[1].split(",").map((x) => parseFloat(x));
  return [p[0], p[1], p[2], p[3] ?? 1];
}

function over(fg, bg) {
  const a = fg[3];
  return [fg[0] * a + bg[0] * (1 - a), fg[1] * a + bg[1] * (1 - a), fg[2] * a + bg[2] * (1 - a), 1];
}

function lum([r, g, b]) {
  const f = (v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}

function ratio(a, b) {
  const [l1, l2] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
}

function color(table, token, base) {
  const c = parse(resolve(table, `var(${token})`), table);
  return c[3] < 1 ? over(c, base ?? parse(resolve(table, "var(--bg-app)"), table)) : c;
}

const surfaces = ["--bg-app", "--bg-panel", "--bg-card", "--bg-elevated"];
const textPairs = [
  ...["--text-header", "--text-main", "--primary-ink", "--success", "--info", "--med", "--high"].flatMap((t) => surfaces.map((s) => [t, s, 4.5, "text"])),
  ...["--crit", "--premium"].flatMap((t) => ["--bg-app", "--bg-panel", "--bg-card"].map((s) => [t, s, 4.5, "text"])),
  ...surfaces.map((s) => ["--text-muted", s, 4.5, "placeholder, disabled, decoration only"]),
  ["--on-premium", "--premium", 4.5, "primary button"],
  ["--on-premium", "--cta-hover", 4.5, "primary button hover"],
  ...surfaces.map((s) => ["--crit-ink", s, 4.5, "danger text in menus"]),
  ["--on-crit", "--crit", 4.5, "danger button"],
  ["--on-primary", "--primary", 3, "check mark, switch thumb (non-text)"],
  ["--chrome-text", "--chrome-bg", 4.5, "chrome"],
  ["--chrome-ink", "--chrome-bg", 4.5, "chrome"],
  ["--chrome-muted", "--chrome-bg", 3, "chrome labels"],
  ["--focus", "--bg-card", 3, "focus ring"],
  ["--focus", "--bg-app", 3, "focus ring"],
  ["--border-hover", "--bg-panel", 3, "input border"],
  ...["--chart-1", "--chart-2", "--chart-3"].map((c) => [c, "--bg-card", 3, "chart series (non-text)"]),
];

const lines = ["# Contrast report", "", "Generated by `node scripts/contrast-report.mjs` from `packages/ui/theme.css`. Translucent tokens are composited over `--bg-app`.", ""];
let fails = 0;
for (const [name, table] of [["Dark", dark], ["Light", light]]) {
  lines.push(`## ${name}`, "", "| Foreground | Background | Ratio | Needs | Use | Result |", "| --- | --- | --- | --- | --- | --- |");
  for (const [fg, bg, need, use] of textPairs) {
    const b = color(table, bg);
    const f = color(table, fg, b);
    const r = ratio(f, b);
    const ok = r >= need;
    const briefCanvas = name === "Light" && bg === "--bg-app" && (fg === "--success" || fg === "--premium");
    const expected = use.includes("decoration") || use.includes("input border") || briefCanvas;
    if (!ok && !expected) fails++;
    lines.push(`| \`${fg}\` | \`${bg}\` | ${r.toFixed(2)} | ${need} | ${use} | ${ok ? "Pass" : expected ? "Known, see note" : "Fail"} |`);
  }
  lines.push("");
}
lines.push(
  "Notes:",
  "",
  "- `--text-muted` is below 4.5:1 on dark surfaces. It is used only for placeholders, disabled controls, keyboard hints and decoration. Secondary information uses `--text-main`.",
  "- In light mode the brief's `--success` and `--premium` fall just under 4.5:1 on the `--bg-app` canvas. Components only place that text on panels and cards, where it passes.",
  "- Input borders sit below 3:1 against panels in dark mode, as the brief's border tokens define. Inputs are also identified by their label, fill and the focus ring, which passes.",
);
mkdirSync(`${root}docs`, { recursive: true });
writeFileSync(`${root}docs/contrast.md`, lines.join("\n") + "\n");
console.log(lines.filter((l) => l.includes("Fail") && !l.includes("Result")).join("\n") || "All required pairs pass.");
console.log(`Unexpected failures: ${fails}. Report written to docs/contrast.md`);
